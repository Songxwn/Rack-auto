let lang = "zh";

function detectLang() {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved === "en" || saved === "zh") return saved;
  } catch (e) {}
  const nav = String((navigator.language || navigator.userLanguage || "zh") || "zh").toLowerCase();
  return nav.startsWith("en") ? "en" : "zh";
}

function t(key, vars) {
  const row = DICT[key];
  let s = row ? row[lang === "en" ? 1 : 0] : key;
  if (vars) {
    s = s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] == null ? "" : String(vars[k])));
  }
  return s;
}

function setLang(next) {
  lang = next === "en" ? "en" : "zh";
  try { localStorage.setItem(LANG_KEY, lang); } catch (e) {}
  applyChrome();
  if (typeof closeModal === "function") closeModal();
  if (typeof authed !== "undefined" && authed && typeof navTo === "function" && typeof current === "string") {
    navTo(current);
  }
}

function applyChrome() {
  document.documentElement.lang = lang === "en" ? "en" : "zh-CN";
  document.querySelectorAll("[data-i18n]").forEach(el => {
    el.textContent = t(el.getAttribute("data-i18n"));
  });
  document.querySelectorAll("[data-i18n-html]").forEach(el => {
    el.innerHTML = t(el.getAttribute("data-i18n-html"));
  });
  document.querySelectorAll(".lang-btn").forEach(btn => {
    const on = btn.getAttribute("data-lang") === lang;
    btn.classList.toggle("on", on);
    btn.setAttribute("aria-pressed", on ? "true" : "false");
  });
  const title = document.querySelector("#title");
  if (title && typeof current === "string") {
    const map = {
      dash: "title.dash", machines: "title.machines", images: "title.images",
      templates: "title.templates", install: "title.install", stress: "title.stress",
      jobs: "title.jobs", boot: "title.boot",
    };
    if (map[current]) title.textContent = t(map[current]);
  }
  const appVer = document.querySelector("#app-ver");
  const ctrlVer = document.querySelector("#ctrl-ver");
  const ver = (appVer && appVer.textContent) || (ctrlVer && ctrlVer.textContent) || "";
  document.title = t("doc.title", { v: (ver && ver !== "—") ? ver : "" }).replace(/\s+·/, " ·");
}

lang = detectLang();
document.addEventListener("click", ev => {
  const btn = ev.target.closest && ev.target.closest(".lang-btn[data-lang]");
  if (!btn) return;
  setLang(btn.getAttribute("data-lang"));
});
if (document.readyState === "loading") {
  document.addEventListener("DOMContentLoaded", applyChrome);
} else {
  applyChrome();
}
